DO $EF$
BEGIN
    IF NOT EXISTS(SELECT 1 FROM "__EFMigrationsHistory" WHERE "MigrationId" = '20260812150713_MakeCarliftTravelStatCorridorUnique') THEN
    WITH ranked AS (
        SELECT "Id",
               "Coefficient",
               "ObservationCount",
               "LastObservedAtUtc",
               MIN("Id") OVER w AS survivor_id,
               COUNT(*)  OVER w AS group_size
        FROM "CarliftTravelStats"
        WHERE "Deleted" = false
          AND "FromZoneId" IS NOT NULL
          AND "ToZoneId" IS NOT NULL
        WINDOW w AS (PARTITION BY "CompanyId", "FromZoneId", "ToZoneId", "HourOfWeek")
    ),
    folded AS (
        SELECT survivor_id,
               SUM(GREATEST("ObservationCount", 0)) AS total_count,
               SUM(CASE WHEN "ObservationCount" > 0 AND "Coefficient" > 0
                        THEN "ObservationCount" * "Coefficient" ELSE 0 END) AS weighted_sum,
               SUM(CASE WHEN "ObservationCount" > 0 AND "Coefficient" > 0
                        THEN "ObservationCount" ELSE 0 END) AS weighted_count,
               MAX("LastObservedAtUtc") AS last_observed
        FROM ranked
        WHERE group_size > 1
        GROUP BY survivor_id
    )
    UPDATE "CarliftTravelStats" s
    SET "Coefficient"       = CASE WHEN f.weighted_count > 0
                                   THEN f.weighted_sum / f.weighted_count
                                   ELSE s."Coefficient" END,
        "ObservationCount"  = f.total_count,
        "LastObservedAtUtc" = f.last_observed,
        "ModifiedTime"      = now()
    FROM folded f
    WHERE s."Id" = f.survivor_id;
    END IF;
END $EF$;

